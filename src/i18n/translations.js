export const normalizeLanguage = (lang) => {
  if (typeof lang !== "string") return "en";
  const lower = lang.trim().toLowerCase();
  if (lower === "ko" || lower.startsWith("ko-")) return "ko";
  if (lower === "zh" || lower.startsWith("zh-")) return "zh";
  return "en";
};

